/**
 * Sync addon UI panels: expansion_data/<addon>/ui/* → frontend/src/addon-panels/<addon>/*
 *
 * 各アドオンが `ui/Panel.tsx` (default export) を持っていれば、本スクリプトが
 * frontend/src/addon-panels/<addon>/ にコピーし、frontend/src/addon-panels.generated.ts に
 * Suspense + lazy import レジストリを生成する。
 *
 * 本体側 AddonManagerModal の AddonCard が `ADDON_PANELS[addon.addon_name]` を引いて
 * 動的レンダーするため、アドオン作者は addon root に `ui/Panel.tsx` を置くだけで済む。
 *
 * 呼び出し: `node scripts/sync-addon-panels.mjs`
 * package.json の predev / prebuild hook で自動実行される。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FRONTEND_DIR = path.resolve(__dirname, "..");
const EXPANSION_DIR = path.resolve(FRONTEND_DIR, "..", "expansion_data");
const TARGET_DIR = path.join(FRONTEND_DIR, "src", "addon-panels");
const REGISTRY_FILE = path.join(FRONTEND_DIR, "src", "addon-panels.generated.ts");

function listAddonPanels() {
    if (!fs.existsSync(EXPANSION_DIR)) {
        console.log("[sync-addon-panels] expansion_data/ not found, skipping");
        return [];
    }
    const entries = fs.readdirSync(EXPANSION_DIR, { withFileTypes: true });
    const panels = [];
    for (const entry of entries) {
        if (!entry.isDirectory()) continue;
        const uiDir = path.join(EXPANSION_DIR, entry.name, "ui");
        const panelPath = path.join(uiDir, "Panel.tsx");
        if (fs.existsSync(panelPath)) {
            panels.push({ name: entry.name, sourceUiDir: uiDir });
        }
    }
    return panels;
}

function safeIdentifier(addonName) {
    return addonName.replace(/[^a-zA-Z0-9_]/g, "_");
}

function copyUiDir(addonName, sourceDir) {
    const destDir = path.join(TARGET_DIR, addonName);
    fs.mkdirSync(destDir, { recursive: true });
    // ui/ 配下のファイルを全部コピー (Panel.tsx + 関連 .tsx / .css / .module.css 等)
    for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
        if (!entry.isFile()) continue;
        const src = path.join(sourceDir, entry.name);
        const dest = path.join(destDir, entry.name);
        fs.copyFileSync(src, dest);
    }
}

function cleanTargetDir() {
    if (fs.existsSync(TARGET_DIR)) {
        fs.rmSync(TARGET_DIR, { recursive: true, force: true });
    }
    fs.mkdirSync(TARGET_DIR, { recursive: true });
}

function generateRegistry(panels) {
    const lines = [
        "// AUTO-GENERATED by frontend/scripts/sync-addon-panels.mjs",
        "// Do not edit manually. Run `npm run sync:addon-panels` to regenerate.",
        "//",
        "// 各アドオン (expansion_data/<addon>/ui/Panel.tsx) を Suspense + lazy import",
        "// で動的読み込みできるレジストリ。AddonCard で参照される。",
        "",
        'import { lazy, type ComponentType } from "react";',
        "",
        "/** AddonCard から各 Panel に渡される props */",
        "export interface AddonPanelProps {",
        "    addon: {",
        "        addon_name: string;",
        "        display_name: string;",
        "        version: string;",
        "        description?: string;",
        "    };",
        "    personas: { id: string; name: string }[];",
        "    /** /api/addon/<addon_name> のプレフィックス */",
        "    addonApiBase: string;",
        "}",
        "",
    ];
    for (const { name } of panels) {
        const id = safeIdentifier(name);
        lines.push(
            `const ${id}_Panel = lazy(() => import("./addon-panels/${name}/Panel"));`
        );
    }
    lines.push("");
    lines.push(
        "export const ADDON_PANELS: Record<string, ComponentType<AddonPanelProps>> = {"
    );
    for (const { name } of panels) {
        const id = safeIdentifier(name);
        lines.push(`    ${JSON.stringify(name)}: ${id}_Panel,`);
    }
    lines.push("};");
    lines.push("");
    fs.writeFileSync(REGISTRY_FILE, lines.join("\n"));
}

function main() {
    cleanTargetDir();
    const panels = listAddonPanels();
    console.log(`[sync-addon-panels] Found ${panels.length} addon panel(s):`);
    for (const { name, sourceUiDir } of panels) {
        const rel = path.relative(FRONTEND_DIR, sourceUiDir);
        console.log(`  - ${name}  (from ${rel})`);
        copyUiDir(name, sourceUiDir);
    }
    generateRegistry(panels);
    const relReg = path.relative(FRONTEND_DIR, REGISTRY_FILE);
    console.log(`[sync-addon-panels] Registry written: ${relReg}`);
}

main();
