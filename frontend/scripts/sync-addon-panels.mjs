/**
 * Sync addon UI panels: expansion_data/<addon>/ui/* → frontend/src/addon-panels/<addon>/*
 *
 * 各アドオンが以下のいずれか (または両方) を持っていれば、本スクリプトが
 * frontend/src/addon-panels/<addon>/ に ui/ 配下をコピーし、
 * frontend/src/addon-panels.generated.ts に Suspense + lazy import レジストリを生成する。
 *
 *   - `ui/Panel.tsx` (default export): AddonCard 末尾に表示するアドオン全体パネル
 *   - `ui/PersonaPanel.tsx` (default export): ParamsSection のペルソナ別設定ブロック内
 *     (ペルソナ選択後、個別設定・OAuth 欄のすぐ下) に表示するペルソナ連動パネル
 *
 * 呼び出し: `node scripts/sync-addon-panels.mjs`
 * package.json の predev / prebuild hook で自動実行される。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FRONTEND_DIR = path.resolve(__dirname, "..");
const EXPANSION_DIR = path.resolve(FRONTEND_DIR, "..", "expansion_data");
const TARGET_DIR = path.join(FRONTEND_DIR, "src", "addon-panels");
const REGISTRY_FILE = path.join(FRONTEND_DIR, "src", "addon-panels.generated.ts");

export function listAddonPanels(expansionDir = EXPANSION_DIR) {
    if (!fs.existsSync(expansionDir)) {
        console.log("[sync-addon-panels] expansion_data/ not found, skipping");
        return [];
    }
    const entries = fs.readdirSync(expansionDir, { withFileTypes: true });
    const panels = [];
    for (const entry of entries) {
        if (!entry.isDirectory()) continue;
        const uiDir = path.join(expansionDir, entry.name, "ui");
        const hasPanel = fs.existsSync(path.join(uiDir, "Panel.tsx"));
        const hasPersonaPanel = fs.existsSync(path.join(uiDir, "PersonaPanel.tsx"));
        if (hasPanel || hasPersonaPanel) {
            panels.push({
                name: entry.name,
                sourceUiDir: uiDir,
                hasPanel,
                hasPersonaPanel,
            });
        }
    }
    panels.sort((a, b) => a.name.localeCompare(b.name));
    return panels;
}

export function safeIdentifier(addonName) {
    return addonName.replace(/[^a-zA-Z0-9_]/g, "_");
}

function copyUiDir(addonName, sourceDir, targetDir = TARGET_DIR) {
    const destDir = path.join(targetDir, addonName);
    fs.mkdirSync(destDir, { recursive: true });
    // ui/ 配下のファイルを全部コピー (Panel.tsx / PersonaPanel.tsx + 関連 .tsx / .css / .module.css 等)
    for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
        if (!entry.isFile()) continue;
        const src = path.join(sourceDir, entry.name);
        const dest = path.join(destDir, entry.name);
        fs.copyFileSync(src, dest);
    }
}

function cleanTargetDir(targetDir = TARGET_DIR) {
    if (fs.existsSync(targetDir)) {
        fs.rmSync(targetDir, { recursive: true, force: true });
    }
    fs.mkdirSync(targetDir, { recursive: true });
}

export function buildRegistrySource(panels) {
    const lines = [
        "// AUTO-GENERATED by frontend/scripts/sync-addon-panels.mjs",
        "// Do not edit manually. Run `npm run sync:addon-panels` to regenerate.",
        "//",
        "// 各アドオン (expansion_data/<addon>/ui/Panel.tsx, PersonaPanel.tsx) を",
        "// Suspense + lazy import で動的読み込みできるレジストリ。AddonManagerModal で参照される。",
        "",
        'import { lazy, type ComponentType } from "react";',
        "",
        "/** AddonCard から各 Panel に渡される props */",
        "export interface AddonPanelProps {",
        "    addon: {",
        "        addon_name: string;",
        "        display_name: string;",
        "        version: string;",
        "        description?: string;",
        "    };",
        "    personas: { id: string; name: string }[];",
        "    /** /api/addon/<addon_name> のプレフィックス */",
        "    addonApiBase: string;",
        "    /**",
        "     * Panel 内部で AddonConfig を書き換えた場合 (= 例: stackchan-addon",
        "     * のペアリング操作で master_token を rotate) に呼ぶ callback。",
        "     * 呼ぶと親 AddonManagerModal が /api/addon/ を再 fetch して",
        "     * props.addon.params を最新値で再描画する。",
        "     */",
        "    onConfigChanged?: () => void | Promise<void>;",
        "}",
        "",
        "/** ParamsSection のペルソナ別設定ブロック内から各 PersonaPanel に渡される props */",
        "export interface AddonPersonaPanelProps {",
        "    addon: {",
        "        addon_name: string;",
        "        display_name: string;",
        "        version: string;",
        "        description?: string;",
        "    };",
        "    /** ペルソナ別設定のプルダウンで現在選択されているペルソナ ID */",
        "    personaId: string;",
        "    /** 選択中ペルソナの表示名 */",
        "    personaName: string;",
        "    personas: { id: string; name: string }[];",
        "    /** /api/addon/<addon_name> のプレフィックス */",
        "    addonApiBase: string;",
        "    onConfigChanged?: () => void | Promise<void>;",
        "    /**",
        "     * ParamsSection で発行中の設定保存リクエストがすべて完了するのを待つ。",
        "     * ボイス ID や話速を変えた直後にテスト合成を叩く前などに呼ぶ。",
        "     */",
        "    flushPendingSaves?: () => Promise<void>;",
        "}",
        "",
    ];

    const panelEntries = panels.filter((p) => p.hasPanel);
    const personaPanelEntries = panels.filter((p) => p.hasPersonaPanel);

    for (const { name } of panelEntries) {
        const id = safeIdentifier(name);
        lines.push(
            `const ${id}_Panel = lazy(() => import("./addon-panels/${name}/Panel"));`
        );
    }
    for (const { name } of personaPanelEntries) {
        const id = safeIdentifier(name);
        lines.push(
            `const ${id}_PersonaPanel = lazy(() => import("./addon-panels/${name}/PersonaPanel"));`
        );
    }
    if (panelEntries.length > 0 || personaPanelEntries.length > 0) {
        lines.push("");
    }

    lines.push(
        "export const ADDON_PANELS: Record<string, ComponentType<AddonPanelProps>> = {"
    );
    for (const { name } of panelEntries) {
        const id = safeIdentifier(name);
        lines.push(`    ${JSON.stringify(name)}: ${id}_Panel,`);
    }
    lines.push("};");
    lines.push("");

    lines.push(
        "export const ADDON_PERSONA_PANELS: Record<string, ComponentType<AddonPersonaPanelProps>> = {"
    );
    for (const { name } of personaPanelEntries) {
        const id = safeIdentifier(name);
        lines.push(`    ${JSON.stringify(name)}: ${id}_PersonaPanel,`);
    }
    lines.push("};");
    lines.push("");

    return lines.join("\n");
}

export function syncAddonPanels({
    expansionDir = EXPANSION_DIR,
    targetDir = TARGET_DIR,
    registryFile = REGISTRY_FILE,
    frontendDir = FRONTEND_DIR,
} = {}) {
    cleanTargetDir(targetDir);
    const panels = listAddonPanels(expansionDir);
    console.log(`[sync-addon-panels] Found ${panels.length} addon UI bundle(s):`);
    for (const { name, sourceUiDir, hasPanel, hasPersonaPanel } of panels) {
        const rel = path.relative(frontendDir, sourceUiDir);
        const kinds = [
            hasPanel ? "Panel" : null,
            hasPersonaPanel ? "PersonaPanel" : null,
        ].filter(Boolean).join(", ");
        console.log(`  - ${name} [${kinds}]  (from ${rel})`);
        copyUiDir(name, sourceUiDir, targetDir);
    }
    fs.writeFileSync(registryFile, buildRegistrySource(panels));
    const relReg = path.relative(frontendDir, registryFile);
    console.log(`[sync-addon-panels] Registry written: ${relReg}`);
    return panels;
}

const isDirectRun = process.argv[1]
    && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (isDirectRun) {
    syncAddonPanels();
}
